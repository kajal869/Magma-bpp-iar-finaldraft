"""Build app/wording/clauses.json (clause title -> wording id) from the clause library.

  python -m extractor.clausebank.make_wording_ids

The id of a clause is the slug of its title, the same rule the issued policies follow (lower case, runs of non-alphanumerics -> '-', cut at 70
characters): checked against the 40 ids of an issued policy, 39 are reproduced exactly (the 40th is a clause that policy added by hand).
Titles that collide on the same slug keep the first; the file lists them under "collisions". The library is private, so the output is git-ignored.
"""
from __future__ import annotations

import json
import re

from . import api

MAX = 70


def slug(title: str) -> str:
    t = re.sub(r"['’‘`]", "", title.lower())          # apostrophes vanish ("Engineer's" -> "engineers"); they do not split the word
    return re.sub(r"[^a-z0-9]+", "-", t).strip("-")[:MAX].strip("-")


def build() -> dict:
    seen, clauses, collisions = {}, [], []
    for t in api.load_library().titles:
        i = slug(t)
        if not i:
            continue
        if i in seen:
            collisions.append({"id": i, "kept": seen[i], "dropped": t})
            continue
        seen[i] = t
        clauses.append({"id": i, "title": t})
    return {"note": "ids are title slugs; generated by extractor/clausebank/make_wording_ids.py", "clauses": clauses, "collisions": collisions}


def main() -> None:
    out = api.WORDING
    out.parent.mkdir(parents=True, exist_ok=True)
    data = build()
    out.write_text(json.dumps(data, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"{len(data['clauses'])} clauses -> {out} ({len(data['collisions'])} slug collisions)")


if __name__ == "__main__":
    main()
